USE ROLE SOC_ADMIN;
USE SCHEMA SECURITY_LAKE.BRONZE;
-- Incremental load from S3 into a bronze table (demo)
CREATE OR REPLACE TABLE DNS_RAW_DEMO (raw VARIANT, src_file STRING, loaded_at TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
COPY INTO DNS_RAW_DEMO (raw, src_file)
  FROM (SELECT $1, METADATA$FILENAME FROM @S3_LOGS/dns/2026/10/)
  FILE_FORMAT = (FORMAT_NAME = 'FF_JSON');
