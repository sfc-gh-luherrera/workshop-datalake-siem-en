  tools:
    - title: "SOC assistant"
      name: "soc_agent"
      type: "CORTEX_AGENT_RUN"
      identifier: "SECURITY_LAKE.GOLD.SOC_AGENT"
      description: "Hunting and incident response questions over the security data lake"
  $$;
