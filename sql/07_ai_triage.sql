-- 4) SOC agent (8.5) with analyst (text to SQL) and runbooks (search)
CREATE OR REPLACE AGENT SOC_AGENT
  COMMENT = 'SOC assistant: natural-language hunting and runbooks'
  FROM SPECIFICATION $$
models:
  orchestration: auto
instructions:
  response: "Answer in English, concisely, citing entities (IP, user, domain) and dates. Show the SQL used."
  orchestration: "Use soc_analyst for questions about alerts, traffic and authentications. Use runbooks for response procedures."
tools:
  - tool_spec:
      type: "cortex_analyst_text_to_sql"
      name: "soc_analyst"
      description: "SOC alerts, network activity (NetFlow, firewall) and authentications (AD, Office 365)"
  - tool_spec:
      type: "cortex_search"
      name: "runbooks"
      description: "SOC incident response runbooks"
tool_resources:
  soc_analyst:
    semantic_view: "SECURITY_LAKE.GOLD.SOC_SEMANTIC_VIEW"
    execution_environment:
      type: warehouse
      warehouse: "SOC_WH"
  runbooks:
    name: "SECURITY_LAKE.GOLD.RUNBOOK_SEARCH"
    max_results: 3
$$;

-- Test via SQL (also available in Snowflake Intelligence and via REST API)
WITH r AS (SELECT TRY_PARSE_JSON(SNOWFLAKE.CORTEX.DATA_AGENT_RUN('SECURITY_LAKE.GOLD.SOC_AGENT',
  '{"messages":[{"role":"user","content":[{"type":"text","text":"Which critical-severity alerts are there and which entity do they affect?"}]}]}')) AS j)
SELECT f.value:text::STRING AS respuesta FROM r, LATERAL FLATTEN(r.j:content) f WHERE f.value:type::STRING = 'text';

-- 5) Managed MCP server (8.1, 5.4): exposes the agent to external MCP clients
CREATE OR REPLACE MCP SERVER SOC_MCP
