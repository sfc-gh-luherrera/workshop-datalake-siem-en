USE ROLE SOC_ADMIN;
USE WAREHOUSE SOC_WH;
USE SCHEMA SECURITY_LAKE.GOLD;

-- 1) Structured alert triage (8.5): JSON with schema -> queryable columns
UPDATE ALERTS SET triage = AI_COMPLETE(
  model => 'claude-sonnet-4-5',
  prompt => 'You are an L2 SOC analyst. Triage this alert in English, concisely. Alert: '
            || TO_JSON(OBJECT_CONSTRUCT('detection', detection, 'entity', entity, 'event_time', event_time, 'details', details)),
  response_format => {'type': 'json', 'schema': {'type': 'object', 'properties': {
      'resumen': {'type': 'string'},
      'tactica_mitre': {'type': 'string'},
      'severidad': {'type': 'string', 'enum': ['baja', 'media', 'alta', 'critica']},
      'siguientes_pasos': {'type': 'array', 'items': {'type': 'string'}}},
    'required': ['resumen', 'tactica_mitre', 'severidad', 'siguientes_pasos']}})
WHERE triage IS NULL;

SELECT detection, entity, triage:severidad::STRING AS severidad, triage:tactica_mitre::STRING AS mitre,
       triage:resumen::STRING AS resumen, triage:siguientes_pasos AS pasos
FROM ALERTS ORDER BY event_time;

-- 2) Runbooks indexed with Cortex Search (RAG over procedures)
CREATE OR REPLACE FILE FORMAT SECURITY_LAKE.BRONZE.FF_WHOLE_FILE
  TYPE = CSV FIELD_DELIMITER = NONE RECORD_DELIMITER = NONE ESCAPE_UNENCLOSED_FIELD = NONE;
CREATE OR REPLACE TABLE RUNBOOKS AS
SELECT SPLIT_PART(METADATA$FILENAME, '/', -1) AS runbook,
       REGEXP_SUBSTR($1, '^# (.*)', 1, 1, 'me', 1) AS title, $1 AS content
FROM @SECURITY_LAKE.BRONZE.S3_LOGS/runbooks/ (FILE_FORMAT => 'SECURITY_LAKE.BRONZE.FF_WHOLE_FILE');

CREATE OR REPLACE CORTEX SEARCH SERVICE RUNBOOK_SEARCH
  ON content ATTRIBUTES title
  WAREHOUSE = SOC_WH TARGET_LAG = '1 day'
  AS SELECT runbook, title, content FROM RUNBOOKS;

SELECT r.value:title::STRING AS title
FROM TABLE(FLATTEN(PARSE_JSON(SNOWFLAKE.CORTEX.SEARCH_PREVIEW('SECURITY_LAKE.GOLD.RUNBOOK_SEARCH',
  '{"query": "How did we handle the last DNS tunnel case?", "columns": ["title"], "limit": 2}')):results)) r;

-- 3) Semantic view for natural-language questions (8.3, 8.4)
CREATE OR REPLACE SEMANTIC VIEW SOC_SEMANTIC_VIEW
  TABLES (
    alerts AS SECURITY_LAKE.GOLD.ALERTS PRIMARY KEY (alert_id) COMMENT = 'SOC alert queue generated by the detections',
    net AS SECURITY_LAKE.SILVER.NETWORK_ACTIVITY COMMENT = 'Network activity: normalized NetFlow and firewall/VPN',
    auth AS SECURITY_LAKE.SILVER.AUTH_ACTIVITY COMMENT = 'Windows/AD authentications and Office 365 activity'
  )
  FACTS (
    net.bytes_out AS bytes_out COMMENT = 'Outbound bytes of the flow'
  )
  DIMENSIONS (
    alerts.detection AS detection COMMENT = 'Detection type: brute_force_success, dns_tunnel, exfiltration, o365_mass_download, ioc_hit, source_silent',
    alerts.entity AS entity COMMENT = 'Affected entity (host, user@ip, host -> domain)',
    alerts.alert_time AS event_time COMMENT = 'Time of the event that triggered the alert',
    alerts.status AS status COMMENT = 'Alert status',
    alerts.severity AS triage:severidad::STRING COMMENT = 'Severity assigned by the AI triage',
    net.src_ip AS src_ip COMMENT = 'Source IP',
    net.dst_ip AS dst_ip COMMENT = 'Destination IP',
    net.dst_port AS dst_port COMMENT = 'Destination port',
    net.net_source AS source COMMENT = 'Source: netflow or fw',
    net.device AS device COMMENT = 'Firewall or VPN that emitted the event',
    net.action AS action COMMENT = 'Firewall action: allow or deny',
    net.net_time AS event_time COMMENT = 'Flow time',
    net.net_unit AS unit COMMENT = 'Business unit (UES, UBR, UDE)',
    auth.user_name AS user_name COMMENT = 'User',
    auth.auth_src_ip AS src_ip COMMENT = 'Source IP of the authentication',
    auth.activity AS activity COMMENT = 'logon_success, logon_failure, special_privileges or O365 operation',
    auth.auth_source AS source COMMENT = 'Source: ad or o365',
    auth.auth_time AS event_time COMMENT = 'Authentication time'
  )
  METRICS (
    alerts.alert_count AS COUNT(alert_id) COMMENT = 'Number of alerts',
    net.total_bytes_out AS SUM(net.bytes_out) COMMENT = 'Total outbound bytes',
    net.flow_count AS COUNT(net.src_ip) COMMENT = 'Number of flows or connections',
    auth.failed_logons AS COUNT_IF(auth.activity = 'logon_failure') COMMENT = 'Failed logons',
    auth.auth_events AS COUNT(auth.user_name) COMMENT = 'Authentication events'
  )
  COMMENT = 'SOC semantic model for natural-language questions';
