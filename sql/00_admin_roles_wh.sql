-- =====================================================================
-- 00 · Database, layers, roles and warehouse
-- Run as ACCOUNTADMIN (or SYSADMIN + SECURITYADMIN)
-- =====================================================================
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS SECURITY_LAKE COMMENT = 'Workshop Security Data Lake';
CREATE SCHEMA IF NOT EXISTS SECURITY_LAKE.BRONZE COMMENT = 'Original event as received (forensics)';
CREATE SCHEMA IF NOT EXISTS SECURITY_LAKE.SILVER COMMENT = 'Normalized common model (OCSF style)';
CREATE SCHEMA IF NOT EXISTS SECURITY_LAKE.GOLD   COMMENT = 'Detections, alerts and use cases';

-- Elastic warehouse: XS by default, multi-cluster for analyst concurrency
CREATE WAREHOUSE IF NOT EXISTS SOC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  MIN_CLUSTER_COUNT = 1
  MAX_CLUSTER_COUNT = 3
  SCALING_POLICY = 'STANDARD'
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Workshop SOC';

-- Functional roles
CREATE ROLE IF NOT EXISTS SOC_ADMIN;
CREATE ROLE IF NOT EXISTS THREAT_HUNTER;
CREATE ROLE IF NOT EXISTS SOC_ANALYST;
GRANT ROLE SOC_ANALYST TO ROLE THREAT_HUNTER;
GRANT ROLE THREAT_HUNTER TO ROLE SOC_ADMIN;
GRANT ROLE SOC_ADMIN TO ROLE SYSADMIN;
SET my_user = CURRENT_USER();
GRANT ROLE SOC_ADMIN TO USER IDENTIFIER($my_user);

GRANT USAGE ON WAREHOUSE SOC_WH TO ROLE SOC_ANALYST;
GRANT OPERATE, MODIFY ON WAREHOUSE SOC_WH TO ROLE SOC_ADMIN;
GRANT OWNERSHIP ON DATABASE SECURITY_LAKE TO ROLE SOC_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE SECURITY_LAKE TO ROLE SOC_ADMIN COPY CURRENT GRANTS;

-- Analyst: read on SILVER and GOLD. Hunter: also BRONZE (forensic raw)
GRANT USAGE ON DATABASE SECURITY_LAKE TO ROLE SOC_ANALYST;
GRANT USAGE ON SCHEMA SECURITY_LAKE.SILVER TO ROLE SOC_ANALYST;
GRANT USAGE ON SCHEMA SECURITY_LAKE.GOLD TO ROLE SOC_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SECURITY_LAKE.SILVER TO ROLE SOC_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA SECURITY_LAKE.SILVER TO ROLE SOC_ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SECURITY_LAKE.SILVER TO ROLE SOC_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SECURITY_LAKE.GOLD TO ROLE SOC_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA SECURITY_LAKE.GOLD TO ROLE SOC_ANALYST;
GRANT USAGE ON SCHEMA SECURITY_LAKE.BRONZE TO ROLE THREAT_HUNTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SECURITY_LAKE.BRONZE TO ROLE THREAT_HUNTER;

-- Cortex AI for the SOC (AI block)
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SOC_ANALYST;

-- Privileges to create tasks, alerts and lifecycle policies
GRANT EXECUTE TASK, EXECUTE ALERT ON ACCOUNT TO ROLE SOC_ADMIN;
GRANT EXECUTE DATA METRIC FUNCTION ON ACCOUNT TO ROLE SOC_ADMIN;   -- without this, DMFs stay SUSPENDED
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE SOC_ADMIN;
GRANT EXECUTE MANAGED TASK ON ACCOUNT TO ROLE SOC_ADMIN;
GRANT APPLY MASKING POLICY, APPLY ROW ACCESS POLICY, APPLY TAG ON ACCOUNT TO ROLE SOC_ADMIN;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE SOC_ADMIN;
